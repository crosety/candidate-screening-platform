import { expect, test } from "@playwright/test";
import { login, selectTenant } from "./helpers";

test("crear un borrador confirma el guardado, persiste y no permite duplicar la referencia", async ({ page }) => {
  await login(page);
  await selectTenant(page, "Grupo Sazón");
  await page.getByRole("link", { name: "Ofertas", exact: true }).click();
  await page.getByRole("link", { name: "Crear oferta", exact: true }).click();
  const key = `ui-draft-${Date.now()}`;
  const title = `Oferta ${key}`;
  await page.getByLabel("Nombre de la oferta", { exact: true }).fill(title);
  await page.getByLabel("Referencia estable", { exact: true }).fill(key);
  await page.getByLabel(/^Puesto, condiciones y requisitos/).fill("Atención al público y disponibilidad de tarde.");
  const saved = page.waitForResponse(r => r.request().method() === "PUT" && r.url().endsWith(`/offers/${key}`));
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  const response = await saved;
  expect(response.ok()).toBe(true);
  expect(response.request().headers()["if-none-match"]).toBe("*");
  const { rev } = await response.json();
  await expect(page.getByRole("status")).toHaveText("Borrador guardado. Falta validar y publicar.");
  await expect(page.locator(".workspace-topbar")).toContainText(`rev ${rev}`);
  await page.reload();
  await expect(page.getByLabel("Nombre de la oferta", { exact: true })).toHaveValue(title);
  await expect(page.getByRole("status")).toHaveText("Borrador guardado. Falta validar y publicar.");
  await page.getByRole("link", { name: "Todas las ofertas", exact: true }).click();
  const card = page.getByRole("article").filter({ has: page.getByRole("heading", { name: title, exact: true }) });
  await expect(card.getByRole("link", { name: "Abrir oferta", exact: true })).toHaveCount(0);
  await page.getByRole("link", { name: "Crear oferta", exact: true }).click();
  await page.getByLabel("Nombre de la oferta", { exact: true }).fill("No reemplazar");
  await page.getByLabel("Referencia estable", { exact: true }).fill(key);
  await page.getByLabel(/^Puesto, condiciones y requisitos/).fill("Otra descripción.");
  const writes: string[] = [];
  page.on("request", r => { if (r.method() === "PUT") writes.push(r.url()); });
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("Ya existe una oferta con esta referencia");
  expect(writes).toEqual([]);
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("link", { name: "Todas las ofertas", exact: true }).click();
  await expect(page.getByRole("heading", { name: title, exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "No reemplazar", exact: true })).toHaveCount(0);
});

test("un perfil desactualizado no borra el nuevo borrador creado en otra pestaña", async ({ page, context }) => {
  await login(page);
  await selectTenant(page, "Grupo Sazón");
  await page.getByRole("link", { name: "Empresa", exact: true }).click();
  const voice = page.getByLabel("Cómo hablar", { exact: true });
  const original = await voice.inputValue();
  await voice.fill(`${original}\nCambio simultáneo no confirmado.`);
  const other = await context.newPage();
  await other.goto(page.url().replace(/\/perfil$/, "/ofertas/crear/nueva"));
  const key = `ui-concurrent-${Date.now()}`;
  await other.getByLabel("Nombre de la oferta", { exact: true }).fill(key);
  await other.getByLabel("Referencia estable", { exact: true }).fill(key);
  await other.getByLabel(/^Puesto, condiciones y requisitos/).fill("Oferta creada desde otro editor.");
  await other.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(other.getByRole("status")).toHaveText("Borrador guardado. Falta validar y publicar.");
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("El borrador ha cambiado");
  await expect(voice).toHaveValue(`${original}\nCambio simultáneo no confirmado.`);
  await page.getByRole("button", { name: "Descartar cambios", exact: true }).click();
  await expect(voice).toHaveValue(original);
  await page.getByRole("link", { name: "Ofertas", exact: true }).click();
  await expect(page.getByRole("heading", { name: key, exact: true })).toBeVisible();
  await other.close();
});
