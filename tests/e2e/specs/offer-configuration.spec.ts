import { expect, test } from "@playwright/test";
import { login, selectTenant } from "./helpers";

test("la oferta reúne datos, encaje y fuentes y conserva la configuración guardada", async ({ page }, testInfo) => {
  await login(page);
  await selectTenant(page, "Grupo Sazón");
  await page.getByRole("link", { name: "Ofertas", exact: true }).click();
  await page.getByRole("link", { name: "Crear oferta", exact: true }).click();
  const key = `configuration-${Date.now()}`;
  await page.getByLabel("Nombre de la oferta", { exact: true }).fill("Cocina — configuración independiente");
  await page.getByLabel("Referencia estable", { exact: true }).fill(key);
  await page.getByLabel("Puesto, condiciones y requisitos", { exact: true }).fill("Cocina profesional, jornada de tarde.");
  await page.getByRole("button", { name: "Entrevista y evaluación", exact: true }).click();
  await page.getByRole("button", { name: "Añadir campo", exact: true }).click();
  const field = page.getByRole("group", { name: /^Dato 1 ·/ });
  await field.getByLabel("Nombre visible para selección", { exact: true }).fill("Experiencia");
  await field.getByLabel("Dato que se pregunta", { exact: true }).fill("Años de experiencia en cocina");
  await field.getByRole("combobox", { name: "Tipo de dato", exact: true }).selectOption("number");
  await field.getByRole("button", { name: "Añadir criterio de encaje", exact: true }).click();
  await field.getByLabel("Criterio profesional", { exact: true }).fill("Dos años de cocina");
  await field.getByRole("combobox", { name: "Condición", exact: true }).selectOption("minimum");
  await field.getByLabel("Valor esperado", { exact: true }).fill("2");
  await page.getByRole("button", { name: "Documentación y herramientas", exact: true }).click();
  await page.getByRole("checkbox", { name: /Manual del repartidor/ }).check();
  await page.getByRole("button", { name: "Probar y publicar", exact: true }).click();
  const preview = page.waitForResponse(r => r.url().endsWith("/offers/preview") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Actualizar vista previa", exact: true }).click();
  const response = await preview;
  expect(response.ok()).toBe(true);
  const effective = await response.json();
  expect(effective.fields).toHaveLength(1);
  expect(effective.sources.map((s: { id: string }) => s.id)).toEqual(["manual_repartidor"]);
  expect(effective.prompt).toContain("Dos años de cocina");
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Borrador guardado");
  await page.reload();
  await page.getByRole("button", { name: "Entrevista y evaluación", exact: true }).click();
  await expect(page.getByLabel("Dato que se pregunta", { exact: true })).toHaveValue("Años de experiencia en cocina");
  await expect(page.getByLabel("Valor esperado", { exact: true })).toHaveValue("2");
  await page.screenshot({ path: testInfo.outputPath("offer-editor.png"), fullPage: true });
  await page.getByRole("button", { name: "Quitar campo", exact: true }).click();
  await page.getByRole("button", { name: "Probar y publicar", exact: true }).click();
  const emptyPreview = page.waitForResponse(r => r.url().endsWith("/offers/preview"));
  await page.getByRole("button", { name: "Actualizar vista previa", exact: true }).click();
  expect((await (await emptyPreview).json()).fields).toEqual([]);
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Borrador guardado");
  await page.getByRole("link", { name: "Empresa", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Fuentes", exact: true })).toHaveCount(0);
  await expect(page.getByRole("tab", { name: "Rúbrica", exact: true })).toHaveCount(0);
  await page.getByRole("link", { name: "Biblioteca", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Biblioteca de documentos", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Simulación", exact: true }).click();
  await page.getByRole("button", { name: "Calidad del agente", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Calidad del agente", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Guardar borrador", exact: true })).toBeVisible();
});

test("heredar y copiar conserva solo criterios compatibles y protege la edición", async ({ page }, testInfo) => {
  await login(page);
  await selectTenant(page, "Grupo Sazón");
  await page.getByRole("link", { name: "Ofertas", exact: true }).click();
  await page.getByRole("link", { name: "Crear oferta", exact: true }).click();
  await page.getByLabel("Nombre de la oferta", { exact: true }).fill("");
  await page.getByRole("button", { name: "Probar y publicar", exact: true }).click();
  await page.getByRole("button", { name: "Actualizar vista previa", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("nombre de la oferta");
  await expect(page.getByLabel("Nombre de la oferta", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("nombre de la oferta");
  await page.getByLabel("Nombre de la oferta", { exact: true }).fill("Herencia controlada");
  await page.getByLabel("Referencia estable", { exact: true }).fill("referencia inválida");
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("Referencia estable");
  const key = `inheritance-${Date.now()}`;
  await page.getByLabel("Referencia estable", { exact: true }).fill(key);
  await page.getByLabel("Puesto, condiciones y requisitos", { exact: true }).fill("Atención en sala, disponibilidad de tarde.");
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("link", { name: "Biblioteca", exact: true }).click();
  await expect(page.getByLabel("Referencia estable", { exact: true })).toHaveValue(key);
  await page.getByRole("button", { name: "Entrevista y evaluación", exact: true }).click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Usar campos comunes", exact: true }).click();
  await page.getByRole("button", { name: "Crear copia independiente", exact: true }).click();
  const field = page.getByRole("group", { name: /^Dato 1 ·/ });
  await field.getByRole("combobox", { name: "Tipo de dato", exact: true }).selectOption("number");
  await field.getByRole("button", { name: "Añadir criterio de encaje", exact: true }).click();
  await field.getByRole("combobox", { name: "Condición", exact: true }).selectOption("minimum");
  await field.getByLabel("Valor esperado", { exact: true }).fill("2");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Usar campos comunes", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Condición", exact: true })).toHaveValue("present");
  await page.getByRole("button", { name: "Probar y publicar", exact: true }).click();
  const preview = page.waitForResponse(r => r.url().endsWith("/offers/preview"));
  await page.getByRole("button", { name: "Actualizar vista previa", exact: true }).click();
  const effective = await (await preview).json();
  expect(effective.fields_origin).toBe("inherit");
  expect(effective.fields[0].value_type).toBe("text");
  await page.getByRole("button", { name: "Puesto y condiciones", exact: true }).click();
  let release!: () => void;
  const wait = new Promise<void>(resolve => { release = resolve; });
  await page.route(`**/offers/${key}`, async route => { await wait; await route.continue(); });
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByLabel("Nombre de la oferta", { exact: true })).toBeDisabled();
  release();
  await expect(page.getByRole("status")).toContainText("Borrador guardado");
  await page.reload();
  await expect(page.getByLabel("Nombre de la oferta", { exact: true })).toHaveValue("Herencia controlada");
  await page.setViewportSize({ width: 375, height: 812 });
  await expect(page.getByLabel("Nombre de la oferta", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
  await page.screenshot({ path: testInfo.outputPath("offer-mobile.png"), fullPage: true });
});
